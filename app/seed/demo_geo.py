"""Reale Geometrie-Stützpunkte für den Demo-Leitungsplan.

Der Demo-Datensatz spielt im Ortskern von **Hagenberg im Mühlkreis (OÖ)**: die
Versorgungsleitungen folgen echten Straßenachsen, die Hausanschlüsse sitzen auf
echten Gebäuden, und die Hauptleitung vom Hochbehälter ins Ortsnetz ist eine
echte Route über das dortige Wegenetz. Dadurch liegt der Plan deckungsgleich auf
dem basemap.at-Hintergrund statt als Reißbrett-Raster frei im Feld.

**Datenherkunft**

* Straßenachsen und Gebäude-Mittelpunkte: © OpenStreetMap-Mitwirkende, Daten
  verfügbar unter der Open Database License (ODbL 1.0),
  https://www.openstreetmap.org/copyright — Auszug vom 2026-09, auf den
  Demo-Ausschnitt beschnitten und per Douglas-Peucker (~2,5 m) vereinfacht.
* Geländehöhen (``*_ELEVATION``): SRTM 30 m via opentopodata.org.

Quellen, Sammelschacht und Hochbehälter sind **erfunden**; ihre Koordinaten
zeigen auf unbebautes Gelände nördlich des Orts und gehören zu keiner realen
Anlage. Ebenso sind sämtliche Kunden-, Objekt- und Verbrauchsdaten des Seeds
frei erfunden — die Hausanschlüsse markieren nur Gebäude-Positionen, keine
Haushalte.

Alle Koordinaten sind ``(lng, lat)`` in WGS84, also dieselbe Achsenreihenfolge
wie in GeoJSON — sie wandern ohne Umsortieren in ``net_svc.apply_geometry``.
Dieses Modul enthält **nur Geometrie**; Namen, Materialien, Baujahre und
Beschreibungen vergibt ``app/seed/demo.py``.

**Reproduktion.** Die Straßenachsen stammen aus einer Overpass-Abfrage der Form

    [out:json];
    way["highway"~"^(residential|unclassified|tertiary|living_street)$"]
       (48.3610,14.5010,48.3760,14.5250);
    out geom;

(Gebäude analog mit ``way["building"]`` und ``out center tags;``, gefiltert auf
``addr:housenumber``). Wege gleichen Namens wurden über gemeinsame Endpunkte
verkettet, auf den Demo-Ausschnitt beschnitten, per Douglas-Peucker mit 2,5 m
vereinfacht und auf sechs Nachkommastellen gerundet. Die Hauptleitung ist ein
Dijkstra-Kürzester-Weg auf demselben Wegenetz. Wer den Ausschnitt austauschen
will, ersetzt dieses Modul komplett — ``demo.py`` liest ausschließlich die hier
definierten Namen.
"""

